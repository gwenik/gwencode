export const defaultMessage = 'Здравствуйте! Пишу с сайта gwensoft.'

export type ContactChannel = 'telegram' | 'whatsapp' | 'phone' | 'channel'

export function buildContactLink(channel: ContactChannel, message = defaultMessage) {
  switch (channel) {
    case 'telegram':
      return `https://t.me/${site.telegram}?text=${encodeURIComponent(message)}`
    case 'channel':
      return `https://t.me/${site.channel}`
    case 'whatsapp':
      return `https://wa.me/${site.whatsapp}?text=${encodeURIComponent(message)}`
    case 'phone':
      return `tel:${site.phone.replace(/[^\d+]/g, '')}`
  }
}

